export function resolveComponentCategoryKind(component = {}) {
  const raw = `${component.category_name || ''} ${component.name || ''} ${component.brand || ''}`.toLowerCase();
  if (raw.includes('gpu') || raw.includes('видеокарт') || raw.includes('rtx') || raw.includes('radeon') || raw.includes('graphics')) {
    return 'gpu';
  }
  if (raw.includes('cpu') || raw.includes('процессор') || raw.includes('ryzen') || raw.includes('core i')) {
    return 'cpu';
  }
  if (raw.includes('motherboard') || raw.includes('материнск') || raw.includes('b650') || raw.includes('z790') || raw.includes('b760')) {
    return 'motherboard';
  }
  if (raw.includes('ram') || raw.includes('memory') || raw.includes('память') || raw.includes('ddr') || raw.includes('dominator') || raw.includes('flare') || raw.includes('vengeance')) {
    return 'memory';
  }
  if (raw.includes('storage') || raw.includes('nvme') || raw.includes('ssd') || raw.includes('990 pro')) {
    return 'storage';
  }
  if (raw.includes('cool') || raw.includes('охлажден') || raw.includes('kraken') || raw.includes('aio')) {
    return 'cooling';
  }
  if (raw.includes('psu') || raw.includes('power') || raw.includes('блок питания') || raw.includes('блоки питания') || raw.includes('gx-850') || raw.includes('rm750')) {
    return 'psu';
  }
  if (raw.includes('case') || raw.includes('chassis') || raw.includes('корпус') || raw.includes('o11') || raw.includes('airflow') || raw.includes('flow') || raw.includes('lancool')) {
    return 'case';
  }
  return 'other';
}

export function getComponentImage(component = {}) {
  if (component.image && typeof component.image === 'string' && component.image.trim() !== '') {
    return component.image;
  }
  const name = `${component.brand || ''} ${component.name || ''}`.toLowerCase();
  if (name.includes('4080') || name.includes('4070') || name.includes('4060') || name.includes('7800 xt') || name.includes('7600')) {
    if (name.includes('ryzen')) return STITCH_IMAGES.ryzen7800x3d;
    return STITCH_IMAGES.rtx4080;
  }
  if (name.includes('ryzen') || name.includes('core i')) return STITCH_IMAGES.ryzen7800x3d;
  if (name.includes('dominator') || name.includes('flare') || name.includes('vengeance') || name.includes('fury')) return STITCH_IMAGES.dominatorRam;
  if (name.includes('990 pro') || name.includes('nvme') || name.includes('ssd')) return STITCH_IMAGES.samsung990;
  if (name.includes('z790') || name.includes('b650') || name.includes('b760') || name.includes('tomahawk')) return STITCH_IMAGES.maximusZ790;
  if (name.includes('o11') || name.includes('4000d') || name.includes('flow') || name.includes('pop mini') || name.includes('lancool')) return STITCH_IMAGES.lianLiO11;
  if (name.includes('gx-850') || name.includes('rm750') || name.includes('pure power') || name.includes('pq1000')) return STITCH_IMAGES.seasonicPsu;
  if (name.includes('kraken') || name.includes('liquid') || name.includes('aio')) return STITCH_IMAGES.kraken360;

  const kind = resolveComponentCategoryKind(component);
  const byKind = {
    gpu: STITCH_IMAGES.rtx4080,
    cpu: STITCH_IMAGES.ryzen7800x3d,
    memory: STITCH_IMAGES.dominatorRam,
    storage: STITCH_IMAGES.samsung990,
    motherboard: STITCH_IMAGES.maximusZ790,
    case: STITCH_IMAGES.lianLiO11,
    psu: STITCH_IMAGES.seasonicPsu,
    cooling: STITCH_IMAGES.kraken360,
  };
  return byKind[kind] || STITCH_IMAGES.rtx4080;
}

